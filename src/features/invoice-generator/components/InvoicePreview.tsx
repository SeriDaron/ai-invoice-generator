import React from "react";
import { Invoice } from "@/core/types/invoice";
import { FileText, Cpu, AlertTriangle, CheckCircle } from "lucide-react";

interface InvoicePreviewProps {
  invoice: Invoice;
}

export const InvoicePreview: React.FC<InvoicePreviewProps> = ({ invoice }) => {
  const isFallback = invoice.metadata.generatedBy === "fallback-engine";

  return (
    <div className="w-full max-w-3xl mx-auto p-6 bg-white border border-slate-200 rounded-xl shadow-sm space-y-6">
      {/* AI status badge */}
      <div className={`p-4 rounded-lg flex items-start gap-3 border ${
        isFallback ? "bg-amber-50 border-amber-200 text-amber-800" : "bg-teal-50 border-teal-200 text-teal-800"
      }`}>
        {isFallback ? (
          <AlertTriangle className="h-5 w-5 text-amber-600 flex-shrink-0 mt-0.5" />
        ) : (
          <Cpu className="h-5 w-5 text-teal-600 flex-shrink-0 mt-0.5" />
        )}
        <div>
          <h4 className="font-semibold text-sm">
            {isFallback ? "Local Fallback Engine Triggered" : "Generated by Local AI Model"}
          </h4>
          <p className="text-xs opacity-90 mt-0.5">
            Processing Time: {invoice.metadata.processingTimeMs}ms | 
            Model Confidence: {(invoice.metadata.confidenceScore * 100).toFixed(0)}%
          </p>
          {invoice.aiNotes && <p className="text-xs italic mt-2 border-t pt-2 border-current/20">{invoice.aiNotes}</p>}
        </div>
      </div>

      {/* Main invoice header */}
      <div className="flex justify-between items-start pt-2">
        <div>
          <div className="flex items-center gap-2 text-slate-900">
            <FileText className="h-6 w-6 text-indigo-600" />
            <span className="text-xl font-bold tracking-tight">{invoice.invoiceNumber}</span>
          </div>
          <p className="text-xs text-slate-500 mt-1">Issue Date: {invoice.issueDate}</p>
          <p className="text-xs text-slate-500">Due Date: {invoice.dueDate}</p>
        </div>
        <div className="text-right">
          <span className="inline-flex items-center px-2.5 py-0.5 rounded-full text-xs font-medium bg-emerald-100 text-emerald-800">
            <CheckCircle className="w-3 h-3 mr-1" /> Issued
          </span>
        </div>
      </div>

      <hr className="border-slate-100" />

      {/* Counterparties */}
      <div className="grid grid-cols-2 gap-8 text-sm">
        <div>
          <span className="text-xs font-semibold text-slate-400 uppercase tracking-wider block mb-1">Bill From</span>
          <p className="font-bold text-slate-800">{invoice.sender.name}</p>
          <p className="text-slate-600 text-xs mt-0.5">{invoice.sender.email}</p>
          <p className="text-slate-500 text-xs mt-1 whitespace-pre-line">{invoice.sender.address}</p>
          {invoice.sender.vatId && <p className="text-slate-400 text-xs mt-1">VAT: {invoice.sender.vatId}</p>}
        </div>
        <div>
          <span className="text-xs font-semibold text-slate-400 uppercase tracking-wider block mb-1">Bill To</span>
          <p className="font-bold text-slate-800">{invoice.receiver.name}</p>
          <p className="text-slate-600 text-xs mt-0.5">{invoice.receiver.email}</p>
          <p className="text-slate-500 text-xs mt-1 whitespace-pre-line">{invoice.receiver.address}</p>
        </div>
      </div>

      {/* Line items table */}
      <div className="border border-slate-100 rounded-lg overflow-hidden mt-4">
        <table className="w-full text-left border-collapse">
          <thead>
            <tr className="bg-slate-50 border-b border-slate-100 text-xs font-semibold text-slate-600">
              <th className="p-3">Description</th>
              <th className="p-3 text-center w-16">Qty</th>
              <th className="p-3 text-right w-24">Rate</th>
              <th className="p-3 text-right w-28">Amount</th>
            </tr>
          </thead>
          <tbody className="text-sm divide-y divide-slate-50 text-slate-700">
            {invoice.items.map((item) => (
              <tr key={item.id}>
                <td className="p-3 font-medium text-slate-800">{item.description}</td>
                <td className="p-3 text-center text-slate-500">{item.quantity}</td>
                <td className="p-3 text-right text-slate-500">
                  {item.price.toLocaleString("en-US", { style: "currency", currency: invoice.currency })}
                </td>
                <td className="p-3 text-right font-semibold text-slate-900">
                  {item.total.toLocaleString("en-US", { style: "currency", currency: invoice.currency })}
                </td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>

      {/* Tax calculation and grand total */}
      <div className="flex justify-end pt-2">
        <div className="w-64 space-y-2 text-sm text-slate-600">
          <div className="flex justify-between">
            <span>Subtotal:</span>
            <span className="font-medium text-slate-900">
              {invoice.subtotal.toLocaleString("en-US", { style: "currency", currency: invoice.currency })}
            </span>
          </div>
          <div className="flex justify-between">
            <span>Tax ({(invoice.taxRate * 100).toFixed(0)}%):</span>
            <span className="font-medium text-slate-900">
              {invoice.taxTotal.toLocaleString("en-US", { style: "currency", currency: invoice.currency })}
            </span>
          </div>
          <div className="flex justify-between pt-2 border-t border-slate-100 text-base font-bold text-slate-900">
            <span>Grand Total:</span>
            <span className="text-indigo-600">
              {invoice.grandTotal.toLocaleString("en-US", { style: "currency", currency: invoice.currency })}
            </span>
          </div>
        </div>
      </div>
    </div>
  );
};
